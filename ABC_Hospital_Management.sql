COUNT(DISTINCT a.patient_id) FILTER (WHERE a.status = 'Completed') AS patients_treated,
COALESCE(SUM(pay.amount_paid),0) AS collected_revenue
FROM doctors doc JOIN departments d ON d.department_id = doc.department_id
LEFT JOIN appointments a ON a.doctor_id = doc.doctor_id
LEFT JOIN payments pay ON pay.appointment_id = a.appointment_id
GROUP BY doc.doctor_id, doc.doctor_name, d.department_name;

SELECT * FROM doctor_performance_report ORDER BY collected_revenue DESC;


WITH monthly AS (
SELECT DATE_TRUNC('month', payment_date)::date AS revenue_month, SUM(amount_paid) AS collected
FROM payments GROUP BY 1)
SELECT revenue_month, collected,
LAG(collected) OVER (ORDER BY revenue_month) AS previous_month,
collected - LAG(collected) OVER (ORDER BY revenue_month) AS change_amount,
ROUND(100.0 * (collected - LAG(collected) OVER (ORDER BY revenue_month)) /
NULLIF(LAG(collected) OVER (ORDER BY revenue_month),0),2) AS change_percent
FROM monthly ORDER BY revenue_month;


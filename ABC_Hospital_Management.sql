INSERT INTO revenue_analytics (revenue_month, total_billed, total_collected, outstanding_balance)
SELECT DATE_TRUNC('month', payment_date)::date, SUM(bill_amount), SUM(amount_paid), SUM(bill_amount - amount_paid)
FROM payments GROUP BY 1
ON CONFLICT (revenue_month) DO UPDATE SET
total_billed = EXCLUDED.total_billed,
total_collected = EXCLUDED.total_collected,
outstanding_balance = EXCLUDED.outstanding_balance;

SELECT * FROM revenue_analytics ORDER BY revenue_month;


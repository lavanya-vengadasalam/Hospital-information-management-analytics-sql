WITH RECURSIVE employee_tree AS (
SELECT employee_id, employee_name, job_title, manager_id, 1 AS hierarchy_level,
employee_name::text AS hierarchy_path
FROM employees WHERE manager_id IS NULL
UNION ALL SELECT e.employee_id, e.employee_name, e.job_title, e.manager_id, t.hierarchy_level + 1,
t.hierarchy_path || ' -> ' || e.employee_name
FROM employees e JOIN employee_tree t ON e.manager_id = t.employee_id)
SELECT employee_id, employee_name, job_title, manager_id, hierarchy_level, hierarchy_path
FROM employee_tree ORDER BY hierarchy_path;


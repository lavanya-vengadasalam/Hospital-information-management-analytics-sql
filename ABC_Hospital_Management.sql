CREATE TABLE departments (
    department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(80) NOT NULL UNIQUE,
    location VARCHAR(80));

CREATE TABLE employees (
    employee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name VARCHAR(120) NOT NULL,
    job_title VARCHAR(80) NOT NULL,
    manager_id INT REFERENCES employees(employee_id),
    department_id INT REFERENCES departments(department_id),
    salary NUMERIC(12,2) NOT NULL CHECK (salary >= 0),
    hire_date DATE NOT NULL DEFAULT CURRENT_DATE,
    email VARCHAR(160) UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE doctors (
    doctor_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_name VARCHAR(120) NOT NULL,
    department_id INT NOT NULL REFERENCES departments(department_id),
    salary NUMERIC(12,2) NOT NULL CHECK (salary >= 0),
    email VARCHAR(160) UNIQUE,
    phone VARCHAR(25),
    hire_date DATE NOT NULL DEFAULT CURRENT_DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE patients (
    patient_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name VARCHAR(120) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(20),
    city VARCHAR(80),
    phone VARCHAR(25),
    email VARCHAR(160),
    registered_at DATE NOT NULL DEFAULT CURRENT_DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE rooms (
    room_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL UNIQUE,
    room_type VARCHAR(40) NOT NULL,
    daily_rate NUMERIC(10,2) NOT NULL CHECK (daily_rate >= 0),
    is_available BOOLEAN NOT NULL DEFAULT TRUE);

CREATE TABLE appointments (
    appointment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    doctor_id INT NOT NULL REFERENCES doctors(doctor_id),
    appointment_date TIMESTAMP NOT NULL,
    status VARCHAR(25) NOT NULL CHECK (status IN ('Scheduled','Completed','Cancelled','No-show')),
    reason VARCHAR(250),
    consultation_fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (consultation_fee >= 0));

CREATE TABLE admissions (
    admission_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    doctor_id INT REFERENCES doctors(doctor_id),
    room_id INT REFERENCES rooms(room_id),
    admission_date DATE NOT NULL,
    discharge_date DATE,
    admission_status VARCHAR(20) NOT NULL DEFAULT 'Admitted',
    CHECK (discharge_date IS NULL OR discharge_date >= admission_date));

CREATE TABLE diagnoses (
    diagnosis_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    doctor_id INT REFERENCES doctors(doctor_id),
    appointment_id INT REFERENCES appointments(appointment_id),
    admission_id INT REFERENCES admissions(admission_id),
    diagnosis_name VARCHAR(160) NOT NULL,
    diagnosis_date DATE NOT NULL DEFAULT CURRENT_DATE,
    treatment_cost NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (treatment_cost >= 0));

CREATE TABLE medicines (
    medicine_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_name VARCHAR(120) NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    expiry_date DATE NOT NULL,
    stock_quantity INT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0));

CREATE TABLE prescriptions (
    prescription_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    doctor_id INT NOT NULL REFERENCES doctors(doctor_id),
    medicine_id INT NOT NULL REFERENCES medicines(medicine_id),
    prescribed_date DATE NOT NULL DEFAULT CURRENT_DATE,
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0));

CREATE TABLE lab_tests (
    lab_test_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    doctor_id INT REFERENCES doctors(doctor_id),
    test_name VARCHAR(120) NOT NULL,
    test_date DATE NOT NULL DEFAULT CURRENT_DATE,
    test_cost NUMERIC(10,2) NOT NULL CHECK (test_cost >= 0),
    result_status VARCHAR(30) DEFAULT 'Pending');

CREATE TABLE insurance (
    insurance_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    provider_name VARCHAR(120) NOT NULL,
    policy_number VARCHAR(100) NOT NULL UNIQUE,
    coverage_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (coverage_amount >= 0),
    valid_until DATE NOT NULL);

CREATE TABLE payments (
    payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    appointment_id INT REFERENCES appointments(appointment_id),
    admission_id INT REFERENCES admissions(admission_id),
    payment_date DATE NOT NULL,
    bill_amount NUMERIC(12,2) NOT NULL CHECK (bill_amount >= 0),
    amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    payment_status VARCHAR(20) GENERATED ALWAYS AS
      (CASE WHEN amount_paid >= bill_amount THEN 'Paid'
            WHEN amount_paid = 0 THEN 'Unpaid' ELSE 'Partial' END) STORED,
    CHECK (amount_paid <= bill_amount));

CREATE TABLE doctor_performance (
    performance_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id INT NOT NULL REFERENCES doctors(doctor_id),
    report_month DATE NOT NULL,
    patients_treated INT NOT NULL DEFAULT 0,
    revenue_generated NUMERIC(12,2) NOT NULL DEFAULT 0,
    UNIQUE (doctor_id, report_month));

CREATE TABLE patient_analytics (
    patient_id INT PRIMARY KEY REFERENCES patients(patient_id),
    appointment_count INT NOT NULL DEFAULT 0,
    admission_count INT NOT NULL DEFAULT 0,
    total_spending NUMERIC(12,2) NOT NULL DEFAULT 0,
    last_visit_date DATE);

CREATE TABLE revenue_analytics (
    revenue_month DATE PRIMARY KEY,
    total_billed NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_collected NUMERIC(14,2) NOT NULL DEFAULT 0,
    outstanding_balance NUMERIC(14,2) NOT NULL DEFAULT 0);

